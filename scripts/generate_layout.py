"""Generate the Studio physical layout from the checked-in PCB point snapshot."""
import argparse, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
COLUMNS = ["pinky", "ring", "middle", "index", "inner"]

def layout():
    points = json.loads((ROOT / "hardware/layout-points.json").read_text())
    order = []
    for row in ["top", "home", "bottom"]:
        order += [("left", f"matrix_{c}_{row}") for c in COLUMNS]
        order += [("right", f"matrix_{c}_{row}") for c in reversed(COLUMNS)]
    order += [("left", "thumb_mid"), ("left", "thumb_far"), ("right", "thumb_far"), ("right", "thumb_mid")]
    # Mirror about the source's inner edge; leave a 60 mm split gap.
    origin = min(p["x"] for p in points.values())
    top = max(p["y"] for p in points.values())
    entries = []
    for side, name in order:
        p = points[name]
        cx = (30 + p["x"] - origin) * (1 if side == "right" else -1)
        cy = top - p["y"]
        angle = -p["r"] if side == "right" else p["r"]
        entries.append({"side": side, "key": name, "cx": cx, "cy": cy, "rotation": angle})
    min_x = min(p["cx"] for p in entries) - 8.75
    for p in entries:
        p["x"] = round((p["cx"] - 8.75 - min_x) / 19 * 100)
        p["y"] = round(p["cy"] / 19 * 100)
        p["rx"] = round((p["cx"] - min_x) / 19 * 100)
        p["ry"] = round((p["cy"] + 8.25) / 19 * 100)
    return entries

def rendered():
    lines = ["// Generated by scripts/generate_layout.py; dimensions normalized to 19 mm.",
             "/ {", "    rt34_layout: rt34_layout {", '        compatible = "zmk,physical-layout";',
             '        display-name = "Tempest MID + FAR / 34 keys";', "        transform = <&rt34_transform>;",
             "        kscan = <&rt34_scan>;", "        keys ="]
    for i, p in enumerate(layout()):
        rot = round(p["rotation"] * 100)
        rotation = str(rot) if rot >= 0 else f"({rot})"
        lines.append(f"            {' ' if i == 0 else ','} <&key_physical_attrs 92 87 {p['x']} {p['y']} {rotation} {p['rx']} {p['ry']}> // {i}: {p['side']} {p['key']}")
    return "\n".join(lines + ["            ;", "    };", "};", ""])

if __name__ == "__main__":
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true"); args = parser.parse_args()
    target = ROOT / "boards/shields/roba_tempest_34/roba_tempest_34-layout.dtsi"
    if args.check:
        assert target.read_text() == rendered(), "Studio layout differs from the PCB point snapshot"
    else:
        target.write_text(rendered())
